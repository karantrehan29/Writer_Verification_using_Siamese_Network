def make_embedding():
    inp_rgb = Input(shape=(150, 150, 3), name='input_image_rgb')
    resnet = ResNet50(weights='imagenet', include_top=False, input_tensor=inp_rgb)
    f1 = Flatten()(resnet.output)

    inp = Input(shape=(150, 150, 1), name='input_image')
    l1 = Conv2D(filters=32, kernel_size=(3,3), activation='relu')(inp)
    l1 = BatchNormalization()(l1)
    m1 = MaxPooling2D((2, 2), padding='same')(l1)

    # Second Block
    l2 = Conv2D(64,(3,3), activation = 'relu')(m1)
    l2 = BatchNormalization()(l2)
    m2 = MaxPooling2D((2, 2), padding='same')(l2)

    # Third Block
    l3 = Conv2D(128,(3,3), activation='relu')(m2)
    l3 = BatchNormalization()(l3)
    m3 = MaxPooling2D((2,2), padding='same')(l3)

    # Final Block
    l4 = Conv2D(256, (3, 3), activation='relu')(m3)
    l4 = BatchNormalization()(l4)
    out = Flatten()(l4)

    # Concatenate CNN and Canny outputs
    x = Concatenate()([f1, out])
    x = Dense(4096, activation='sigmoid')(x)
    return Model(inputs=[inp_rgb, inp], outputs=x, name='ResNet_Laplacian')

