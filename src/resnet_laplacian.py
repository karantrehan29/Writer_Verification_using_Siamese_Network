class Distance(Layer):

    # Init method - Inheritance
    def __init__(self, **kwargs):
        super().__init__()

    #  Similarity Calculation
    def call(self, input_layer, validation_layer):
        return tf.math.abs(input_layer - validation_layer)


def make_Siamese_Model():
    input_image_rgb = Input(shape=(150,150,3), name='input_image_rgb')
    input_image_laplacian = Input(shape=(150,150,1), name='input_image_laplacian')
    validation_image_rgb = Input(shape=(150,150,3), name='validation_image_rgb')
    validation_image_laplacian = Input(shape=(150,150,1), name='validation_image_laplacian')

    distance_layer = Distance()
    siamese_model = make_embedding()
    distances = distance_layer(siamese_model([input_image_rgb, input_image_laplacian]), siamese_model([validation_image_rgb, validation_image_laplacian]))

    # Classifier Layer
    classifier = Dense(1, activation='sigmoid')(distances)

    return Model(inputs=[input_image_rgb, input_image_laplacian, validation_image_rgb, validation_image_laplacian], outputs=classifier, name='SiameseNetwork')

