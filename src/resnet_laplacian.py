            if pred_val == test_pair[1][i]:
                if pred_val == 1:
                    true_positive += 1
                else:
                    true_negative += 1
                correct += 1
            else:
                if pred_val == 0:
                    false_negative += 1
                else:
                    false_positive += 1
                incorrect += 1
