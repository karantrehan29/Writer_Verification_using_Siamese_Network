class SiameseTrainDataGenerator(tf.keras.utils.Sequence):

    def __init__(self, batch_size=16, shuffle=True):
        self.batch_size = batch_size
        self.shuffle = shuffle
        self.data_dir = path_IAM_class
        self.writer_list = sorted(os.listdir(self.data_dir))
        self.img_size = (150, 150)
        self.channels = 3
        self.num_samples = sum(len(os.listdir(os.path.join(self.data_dir, writer_id))) for writer_id in self.writer_list) * 2 # Each image will one genuine and one forged case
        self.writer_lines_list = self.store_image_paths()
        self.on_epoch_end()

    def store_image_paths(self):
      writer_lines_list = []
      for writer_id in self.writer_list:
          writer_dir = os.path.join(self.data_dir, writer_id)
          image_list = os.listdir(writer_dir)
          for image_name in image_list:
              image_path = os.path.join(writer_dir, image_name)
              writer_lines_list.append(image_path)
      return writer_lines_list


    def __len__(self):
        return int(np.ceil(self.num_samples / float(self.batch_size)))

    def __getitem__(self, idx):
        indexes = self.indexes[idx*self.batch_size : (idx+1)*self.batch_size]
        writer_pairs = [self.get_writer_pair(idx) for idx in indexes]
        X1_rgb, X1_edge, X2_rgb, X2_edge, Y = self.__data_generation(writer_pairs)
        return [X1_rgb, X1_edge, X2_rgb, X2_edge], Y

    def on_epoch_end(self):
        self.indexes = np.arange(self.num_samples)
        if self.shuffle:
            np.random.shuffle(self.indexes)

    def get_writer_pair(self, idx):
        img1_path = self.writer_lines_list[idx//2]
        if idx % 2 == 0:
            img2 = np.random.choice(os.listdir(os.path.join(self.data_dir, img1_path.split('/')[-2])))
            while img2 == img1_path.split('/')[-1]:
              img2 = np.random.choice(os.listdir(os.path.join(self.data_dir, img1_path.split('/')[-2])))
            img2_path = os.path.join(self.data_dir, img1_path.split('/')[-2], img2)
            label = 1
        else:
            img_folder = np.random.choice(self.writer_list)
            while img_folder ==  img1_path.split('/')[-2]:
              img_folder = np.random.choice(self.writer_list)
            img2_path = os.path.join(self.data_dir, img_folder, np.random.choice(os.listdir(os.path.join(self.data_dir, img_folder))))
            label = 0
        # print(img1_path, img2_path, label)
        return img1_path, img2_path, label


    def __data_generation(self, writer_pairs):
        X1_rgb = np.empty((self.batch_size, *self.img_size, self.channels))
        X1_edge = np.empty((self.batch_size, *self.img_size, 1))
        X2_rgb = np.empty((self.batch_size, *self.img_size, self.channels))
        X2_edge = np.empty((self.batch_size, *self.img_size, 1))
        Y = np.empty((self.batch_size,), dtype=int)
        for i, (img1_path, img2_path, label) in enumerate(writer_pairs):
            X1_rgb[i,], X1_edge[i,] = self.load_image(img1_path)
            X2_rgb[i,], X2_edge[i,] = self.load_image(img2_path)
            Y[i] = label
        return self.preprocess_images(X1_rgb), self.preprocess_images(X1_edge), self.preprocess_images(X2_rgb), self.preprocess_images(X2_edge), Y

    def load_image(self, img_path):
        img = tf.keras.preprocessing.image.load_img(img_path, target_size=None, interpolation='bilinear')
        img = img.resize(self.img_size, resample=Image.BILINEAR)
        img = tf.keras.preprocessing.image.img_to_array(img)
        # img_eroded = cv2.erode(img, None, iterations=1)
        # img = cv2.dilate(img_eroded, None, iterations=1)
        # img = img.astype(np.uint8)
        # img = cv2.fastNlMeansDenoisingColored(img, None, h=10, hColor=10, templateWindowSize=7, searchWindowSize=21)


        img_gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
        img_gray_u = img_gray.astype(np.uint8) # Convert to 8-bit unsigned integer

        img_laplacian = cv2.Laplacian(img_gray_u, cv2.CV_64F, 3)
        img_edge = np.expand_dims(img_laplacian, axis=-1)  # Add channel dimension
        return img, img_edge

    def preprocess_images(self, images):
        images = images.astype(np.float32)
        images /= 255.0
        images = np.nan_to_num(images, nan=0.0, posinf=1.0, neginf=0.0)
        return images

