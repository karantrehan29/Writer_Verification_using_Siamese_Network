# Define the TinyResNet architecture
def tiny_resnet(input_shape):
    n = 1  # Number of residual blocks per stack

    inputs = Input(shape=input_shape)
    x = Conv2D(16, kernel_size=(3, 3), strides=(1, 1), padding='same', activation='relu')(inputs)

    for _ in range(2 * n):
        shortcut = x
        x = Conv2D(16, kernel_size=(3, 3), strides=(1, 1), padding='same', activation='relu')(x)
        x = Conv2D(16, kernel_size=(3, 3), strides=(1, 1), padding='same', activation='relu')(x)
        x = tf.keras.layers.Add()([x, shortcut])
        x = tf.keras.layers.Activation('relu')(x)

    x = Conv2D(32, kernel_size=(3, 3), strides=(2, 2), padding='same', activation='relu')(x)
    for _ in range(2 * n):
        shortcut = x
        x = Conv2D(32, kernel_size=(3, 3), strides=(1, 1), padding='same', activation='relu')(x)
        x = Conv2D(32, kernel_size=(3, 3), strides=(1, 1), padding='same', activation='relu')(x)
        x = tf.keras.layers.Add()([x, shortcut])
        x = tf.keras.layers.Activation('relu')(x)

    x = Conv2D(64, kernel_size=(3, 3), strides=(2, 2), padding='same', activation='relu')(x)
    for _ in range(2 * n):
        shortcut = x
        x = Conv2D(64, kernel_size=(3, 3), strides=(1, 1), padding='same', activation='relu')(x)
        x = Conv2D(64, kernel_size=(3, 3), strides=(1, 1), padding='same', activation='relu')(x)
        x = tf.keras.layers.Add()([x, shortcut])
        x = tf.keras.layers.Activation('relu')(x)

    x = Flatten()(x)
    return inputs, x

